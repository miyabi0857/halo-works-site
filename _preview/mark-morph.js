function markPath(b) {
  var CX = MARK.cx, STEP = MARK.step, BASE0 = MARK.base0;
  var d = '', first = null;
  for (var k = 0; k < 9; k++) {
    var src, dst, u;
    if (b <= 0.5) { src = MARK.gear;     dst = MARK.logo[k]; u = b / 0.5; }
    else          { src = MARK.logo[k];  dst = MARK.flower;  u = (b - 0.5) / 0.5; }
    var base = BASE0 + STEP * k, p = [];
    for (var i = 0; i < 8; i++) {
      var a = src[i][0] + (dst[i][0] - src[i][0]) * u;
      var r = src[i][1] + (dst[i][1] - src[i][1]) * u;
      var t = (base + a) * Math.PI / 180;
      p.push([CX + r * Math.cos(t), CX + r * Math.sin(t)]);
    }
    if (k === 0) { first = p[0]; d += 'M' + first[0].toFixed(2) + ',' + first[1].toFixed(2); }
    d += ' Q' + p[1][0].toFixed(2) + ',' + p[1][1].toFixed(2) + ' ' + p[2][0].toFixed(2) + ',' + p[2][1].toFixed(2)
       + ' Q' + p[3][0].toFixed(2) + ',' + p[3][1].toFixed(2) + ' ' + p[4][0].toFixed(2) + ',' + p[4][1].toFixed(2)
       + ' Q' + p[5][0].toFixed(2) + ',' + p[5][1].toFixed(2) + ' ' + p[6][0].toFixed(2) + ',' + p[6][1].toFixed(2)
       + ' A36.00,36.00 0 0 1 ' + p[7][0].toFixed(2) + ',' + p[7][1].toFixed(2);
  }
  return d + ' Z M80.00,80.00 m-13.00,0 a13.00,13.00 0 1,0 26.00,0 a13.00,13.00 0 1,0 -26.00,0 Z';
}
